  /**
   * NAME: getFeeGasStation
   * PARAMS: receiverAddress
   * get gasPrice fastest on gas Station
   * RETURN
   */
  static async getFeeGasStation (toAddress, countPercent) {
    try {
    // Check whether the receiver is external account or smart contract
      let gasPrice = await EtherGas.getGasPriceFastest()
      if (gasPrice) {
        gasPrice *= countPercent
        let gasPrice1 = Settings.gas.externalFee * gasPrice
        console.log('estimate gasPrice: ', gasPrice1, gasPrice, countPercent)
        return gasPrice1
      } else {
        return 0
      }
    } catch (error) {
      throw error
    }
  }

  static async getGasLimit (toAddress) {
    try {
      // Check whether the receiver is external account or smart contract
      let code = await EtherscanServices.getCode(toAddress)

      if (code === '0x') {
        return Settings.gas.externalFee
      } else if (toAddress.toLowerCase() === HBWALLET) {
        // HB Wallet Infinity Token
        return Settings.gas.externalLargeFeeToken
      } else {
        // Token Standards
        return Settings.gas.externalFeeToken
      }
    } catch (error) {
      throw error
    }
  }

  static async getGasLimitToken (contractAddress, gasPrice, data) {
    try {
      // Check whether the receiver is external account or smart contract
      let limit = '0xffffffffffff'
      let estimateGas = await EtherscanServices.estimateGasToken(contractAddress, data, gasPrice, limit)
      let gasLimit = parseInt(estimateGas)
      console.log('getGasLimitToken: ', gasLimit)
      return gasLimit + Settings.gas.externalFeeToken
    } catch (error) {
      throw error
    }
  }

  static async sendEtherAction (senderAddress, senderPrivateKey, receiverAddress, sendAmount, countPercent) {
    let privateKey = Buffer.from(senderPrivateKey, 'hex')
    // Get the neccessary information to create raw transaction
    let nonce = await EtherscanServices.getNounce(senderAddress)
    let gasPrice = await EtherGas.getGasPriceFastest()
    console.log('sendEtherAction---gasPrice: ', gasPrice)
    gasPrice *= countPercent
    console.log('sendEtherAction---gasPrice1: ', gasPrice)
    let value = bigInt(convertBalanceToWei(sendAmount))
    let gasLimit = await this.getGasLimit(receiverAddress)

    let data = ''
    // Create raw transaction
    gasPrice = bigInt(gasPrice)
    console.log('sendEtherAction---gasPrice2: ', gasPrice)
    console.log('send ether nonce: ', nonce)
    let rawTransaction = {
      data: data,
      nonce,
      to: receiverAddress,
      value: converter.decToHex(value.toString().split('.')[0]),
      gasPrice: '0x' + gasPrice.toString(16),
      gasLimit: '0x' + gasLimit.toString(16)
    }
    // Create transaction and sign with private key
    var transaction = new EthereumTx(rawTransaction)
    transaction.sign(privateKey)

    // Serialize and convert transaction to hex
    let serializedTransaction = transaction.serialize()
    let hexSerializedTransaction = '0x' + serializedTransaction.toString('hex')
    // return HBScan.sendRawTransaction(hexSerializedTransaction)
    return hexSerializedTransaction
  }

