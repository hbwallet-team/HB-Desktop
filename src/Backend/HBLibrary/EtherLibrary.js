  static async sendTokenAction (senderAddress, senderPrivateKey, receiverAddress,
    sendAmount, contractAddress, decimal, countPercent) {
    let privateKey = Buffer.from(senderPrivateKey, 'hex')
    // Get the neccessary information to create raw transaction
    // let nonce = await HBScan.getNounce(senderAddress)
    let nonce = await EtherscanServices.getNounce(senderAddress)
    // let gasPrice = await EtherGasStation.getGasPrice()
    let gasPrice = await EtherGas.getGasPriceFastest()
    gasPrice *= countPercent
    gasPrice = parseFloat(gasPrice.toFixed(0))

    var tokenAmount = bigInt(convertBalanceToWei(sendAmount, decimal))

    // Token Standards
    var transferOpCode = '0xa9059cbb'

    var ethNakedAddress = receiverAddress.toLowerCase().replace('0x', '')

    // Convert to address Token
    var ABIAddressTarget = this.zeroPadLeft(ethNakedAddress, 64)

    // Convert to value Token
    var ABIValueToTransfer = this.zeroPadLeft(converter.decToHex(tokenAmount.toString().split('.')[0]).replace('0x', ''), 64)
    var ethData = transferOpCode + ABIAddressTarget + ABIValueToTransfer
    let gasLimit = await HBScanServices.getGasLimit(senderAddress, nonce, contractAddress, ethData)
    // Create raw transaction
    let rawTransaction = {
      nonce,
      gasPrice: '0x' + gasPrice.toString(16),
      gasLimit: '0x' + gasLimit.toString(16),
      to: contractAddress,
      value: 0,
      data: ethData
    }
    // Create transaction and sign with private key
    var transaction = new EthereumTx(rawTransaction)
    transaction.sign(privateKey)

    // Serialize and convert transaction to hex
    let serializedTransaction = transaction.serialize()
    let hexSerializedTransaction = '0x' + serializedTransaction.toString('hex')
    // return HBScan.sendRawTransaction(hexSerializedTransaction)
    return hexSerializedTransaction
  }

